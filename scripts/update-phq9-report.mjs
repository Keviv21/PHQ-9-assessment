import { readFile, writeFile } from 'node:fs/promises';
import { contentHash, hashBytes, normalizeDefinition, scoringRuntimeHash } from '../src/assessment-content.js';
import { phq9Id } from '../src/report-profiles.js';
const source = process.argv[2];
if (!source) throw new Error('Pass the original all-assessments.json path.');
const sourceBytes = await readFile(source), bundleHash = hashBytes(sourceBytes);
const original = JSON.parse(sourceBytes).assessments.find(d => d.assessment_id === phq9Id);
const file = new URL('../data/assessment-library.json', import.meta.url);
const library = JSON.parse(await readFile(file, 'utf8'));
if (library.bundleHash !== bundleHash) throw new Error('Source differs from this runtime library.');
const index = library.records.findIndex(d => d.id === phq9Id), previous = library.records[index];
if (!previous || previous.assets.length) throw new Error('Unexpected PHQ-9 source or selected assets; review before updating.');
const runtime = normalizeDefinition(original, { bundleHash, verified: previous.verification.contentVerified });
if (scoringRuntimeHash(runtime) !== previous.runtimeHash) throw new Error('Report update must not change questions or scoring.');
const { versionId, sourceSha256, ...runtimeContent } = runtime;
runtime.versionId = contentHash({ raw: original, displayAssets: [], runtimeContent });
library.records[index] = runtime;
const { records, ...header } = library;
const output = `${JSON.stringify(header).slice(0, -1)},"records":[\n${records.map(r => JSON.stringify(r)).join(',\n')}\n]}\n`;
await writeFile(file, output); await writeFile(new URL('../data/assessment-library.json.sha256', import.meta.url), hashBytes(output)+'\n');
console.log(`Updated PHQ-9 report profile ${runtime.reporting.visualProfile.version}; scoring hash unchanged; other ${records.length-1} definitions preserved.`);
